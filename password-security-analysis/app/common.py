def comparison_groups():
    """system_a_vs_b.csv summarised into one row per group, in a fixed order:
    the 8 test groups and the challenge set split into seen / unseen words.
    Columns: group, truth (weak/strong), n, a, b (= share flagged as weak)."""
    t = table("system_a_vs_b")
    if t is None:
        return None
    rows = []
    test = t[t.split == "test"].set_index("stratum")
    for s in STRATUM_ORDER:
        if s in test.index:
            r = test.loc[s]
            rows.append({"group": STRATUM_NAMES[s], "short": SHORT_NAMES[s], "truth": "weak" if r.true_label == 1 else "strong",
                         "n": int(r.n), "a": r.system_a_pct_predictable, "b": r.system_b_pct_predictable})
    ch = t[t.split == "challenge"]
    for vocab, label in [("seen", "Challenge · words in dictionary"),
                         ("unseen", "Challenge · words NOT in dictionary")]:
        part = ch[ch.vocab == vocab]
        if len(part):
            w = part.n / part.n.sum()
            rows.append({"group": label, "short": SHORT_NAMES[vocab], "truth": "weak", "n": int(part.n.sum()),
                         "a": (part.system_a_pct_predictable * w).sum(),
                         "b": (part.system_b_pct_predictable * w).sum()})
    df = pd.DataFrame(rows)
    # weak groups first, then strong ones
    df["order"] = df.truth.map({"weak": 0, "strong": 1})
    return df.sort_values("order", kind="stable").drop(columns="order").reset_index(drop=True)


def ab_group_figure(groups, height=460, correct=False):
    """Grouped bars: System A vs System B per group.
    correct=False -> % flagged as weak; correct=True -> % classified correctly."""
    g = groups.copy()
    if correct:
        flip = g.truth == "strong"
        g.loc[flip, "a"] = 1 - g.loc[flip, "a"]
        g.loc[flip, "b"] = 1 - g.loc[flip, "b"]
    labels = list(g.short)
    fig = go.Figure()
    for col, name, color in [("a", "System A (rules)", COLOR_A), ("b", "System B (ML)", COLOR_B)]:
        fig.add_bar(x=labels, y=g[col] * 100, name=name, marker_color=color,
                    text=[f"{v * 100:.0f}%" for v in g[col]], textposition="outside",
                    textfont=dict(size=12), cliponaxis=False, customdata=list(zip(g.group, g.n)),
                    hovertemplate="%{customdata[0]}<br>" + name + ": %{y:.1f}%<br>n = %{customdata[1]:,}<extra></extra>")
    n_weak = int((g.truth == "weak").sum())
    if 0 < n_weak < len(g):
        fig.add_vline(x=n_weak - 0.5, line_dash="dash", line_color="#5fa3e0")
        fig.add_annotation(x=(n_weak - 1) / 2, y=118, text="<b>Really WEAK</b>", showarrow=False,
                           font=dict(color="#ff9b9b", size=15))
        fig.add_annotation(x=n_weak + (len(g) - n_weak - 1) / 2, y=118, text="<b>Really STRONG</b>",
                           showarrow=False, font=dict(color="#6fe0b5", size=15))
    style(fig, height=height)
    fig.update_layout(barmode="group", bargap=0.25,
                      yaxis=dict(range=[0, 128], tickvals=[0, 25, 50, 75, 100], ticktext=["0%", "25%", "50%", "75%", "100%"],
                                 title="% classified correctly" if correct else "% flagged as weak"))
    fig.update_xaxes(tickangle=0, tickfont=dict(size=12))
    return fig


def metric_row(subset="test"):
    """System A and the selected System B model, one row each, for a subset."""
    a, m = table("rule_based_metrics"), table("ml_metrics")
    if a is None or m is None:
        return None
    best = selected_model_name()
    ra = a[a.subset == subset].iloc[0]
    rb = m[(m.subset == subset) & (m.model == best)].iloc[0]
    return ra, rb
