# ---- loaders ---------------------------------------------------------------
@st.cache_data
def table(name):
    """A table from reports/tables/ (None if the pipeline has not made it)."""
    path = TABLES / f"{name}.csv"
    return pd.read_csv(path, keep_default_na=False) if path.exists() else None


@st.cache_data
def features_df():
    path = PROCESSED / "password_features.csv"
    if not path.exists():
        return None
    return pd.read_csv(path, keep_default_na=False, dtype={"family_id": str, "vocab": str})


@st.cache_data
def ml_predictions():
    path = PROCESSED / "ml_predictions.csv"
    return pd.read_csv(path) if path.exists() else None


@st.cache_data
def clean_passwords():
    """Set of every password in our dataset, to tell the user whether the one
    they typed is in the leaked sample. Kept in memory only."""
    path = PROCESSED / "passwords_clean.csv"
    if not path.exists():
        return None
    df = pd.read_csv(path, keep_default_na=False, dtype={"password": str},
                     usecols=["password", "source"])
    return dict(zip(df.password, df.source))


@st.cache_resource
def load_model(name):
    path = MODELS / f"{name}.joblib"
    return joblib.load(path) if path.exists() else None


def feature_names():
    df = features_df()
    if df is not None:
        return [c for c in df.columns if c not in NON_FEATURE_COLUMNS]
    return list(FEATURE_INFO)


def selected_model_name():
    m = table("ml_metrics")
    if m is None:
        return "random_forest"
    sel = m[m.selected.astype(str) == "True"]
    return sel.model.iloc[0] if len(sel) else "random_forest"


def need(*objs, what="this page"):
    """Stop the page with a clear message if the pipeline has not been run."""
    if any(o is None for o in objs):
        st.warning(f"The data for {what} is missing. Run the pipeline first:\n\n"
                   "`docker compose run --rm pipeline`  or the steps in the README.")
        st.stop()


# ---- layout helpers ----------------------------------------------------------
def style(fig, height=420, legend=True):
    fig.update_layout(
        template="plotly_dark", paper_bgcolor="rgba(0,0,0,0)", plot_bgcolor="rgba(0,0,0,0)",
        font=dict(color=TEXT, size=14), height=height, margin=dict(l=10, r=10, t=40, b=10),
        legend=dict(orientation="h", yanchor="bottom", y=1.02, x=0) if legend else None,
        showlegend=legend, hoverlabel=dict(bgcolor=PANEL),
    )
    fig.update_xaxes(gridcolor=GRID, zerolinecolor=GRID)
    fig.update_yaxes(gridcolor=GRID, zerolinecolor=GRID)
    return fig


def kpi(label, value, sub="", color=TEXT, size=None):
    fs = f"font-size:{size};" if size else ""
    st.markdown(
        f"""<div class="kpi"><div class="kl">{label}</div>
        <div class="kv" style="color:{color};{fs}">{value}</div><div class="ks">{sub}</div></div>""",
        unsafe_allow_html=True)


def confusion_figure(tp, fn, fp, tn, title=""):
    z = [[tp, fn], [fp, tn]]
    text = [[f"TP<br><b>{tp:,}</b>", f"FN<br><b>{fn:,}</b>"],
            [f"FP<br><b>{fp:,}</b>", f"TN<br><b>{tn:,}</b>"]]
    colors = [[0, BAD], [0.5, MEDIUM], [1, GOOD]]
    # colour by correctness, not by size: diagonal green, errors red/amber
    zc = [[1, 0], [0.5, 1]]
    fig = go.Figure(go.Heatmap(z=zc, text=text, texttemplate="%{text}", textfont=dict(size=18, color="#0b1f36"),
                               x=["Says weak", "Says strong"], y=["Really weak", "Really strong"],
                               colorscale=colors, showscale=False, hoverinfo="skip", xgap=6, ygap=6))
    fig.update_yaxes(autorange="reversed")
    style(fig, height=300, legend=False)
    fig.update_layout(title=dict(text=title, font=dict(size=15)))
    return fig


